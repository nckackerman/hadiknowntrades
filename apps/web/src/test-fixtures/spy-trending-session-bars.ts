// `results/beat-the-bench/pool/{id}.json` objects, resolved through that
// same run's `results/mystery-index.json`). Real Yahoo five-minute
// closes, not synthetic and not hand-tuned.
//
// They exist because issue #132's percentile simulation
// (`beat-the-bench-percentile.ts`) makes a directional claim that a
// single flat fixture cannot test: buy-and-hold should rank *differently*
// against a field of randomly-timed togglers depending on which way the
// session went. A random toggler spends part of the day in cash, so on an
// up day sitting out costs them and buy-and-hold ranks high; on a down day
// sitting out saves them and buy-and-hold ranks low. Two real sessions
// with real, opposite drift are what make that assertion mean something.
//
// `spy-session-bars.ts` (the +0.053% 2026-08-26 session) stays the
// fixture for the mechanic's own invariants -- it is deliberately a quiet
// day, which is exactly wrong for this test and exactly right for that one.

